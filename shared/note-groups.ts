// The work for the notes writers: the code files of a repo that need notes, in groups of about 400 lines of whole files. A file of 400 to 600 lines is a
// group of its own, whole. A longer file is cut into parts of about 400 lines, each a group of its own, so that several writers write it at the same time:
// a cut stands only between two definitions, never inside a function. The writer of a part saves only its lines (`ranges` of add-notes).
// The groups of each kind of writer are listed largest first: the longest work starts with the first writers, not at the end.

import { createHash } from 'node:crypto';
import { definitionsOf } from './definitions';
import { fileText, lineCount, repoFiles } from './git';
import { mapSource, notesOfFile, type NoteSource } from './notes-beside-code';
import type { Note } from './change-file';
import { goneSteps, noteKeys, notesInNoProcess, notesNeedingProcess, processFacts } from './processes';
import type { RepoMap } from './repo-map';
import type { StoredMap } from './store';

/** The endings of the names of code files. Everything else (data, text, lock files, pictures) gets no notes. The one list for the rule. */
const CODE_ENDINGS = /\.(ts|tsx|js|jsx|mjs|cjs|vue|svelte|py|ipynb|rb|go|rs|java|kt|kts|scala|swift|c|h|cc|cpp|hpp|cs|php|sh|bash|zsh|sql|r|lua|pl|ex|exs|erl|hs|ml|dart|zig|jl|m|mm)$/i;
const GENERATED_NAME = /\.(min\.(js|css)|d\.ts)$|\.pb\.go$|_pb2(_grpc)?\.py$|\.generated\./i;
const GENERATED_MARK = /@generated|auto-?generated|automatically generated|generated by|do not edit/i; // in the first lines of a generated file
const DRAFT_NAME = /^apostil-[a-z]+-.*\.json$/; // the draft of a writer is no code

export const MAX_FILE_LINES = 20000; // a file with more lines is left out
const GROUP_LINES = 400; // the size that a group grows to; a longer file is a group of its own
const LONG_FILE = 600; // a code file with more lines is cut into parts
const PART_LINES = 400; // the size of a part
const PART_REACH = 150; // how far a cut may stand from 400 lines, and the fewest lines of a last part
const ENOUGH = 0.8; // a file keeps its notes while this share of them still stands at the text of their lines

/** Groups largest first, by the size that `size` gives; groups of the same size keep their order (the order of the areas, then of the paths). */
export const largestFirst = <T>(groups: T[], size: (group: T) => number): T[] => groups.map((group, at) => ({ group, at, size: size(group) }))
  .sort((a, b) => b.size - a.size || a.at - b.at).map((one) => one.group);

/** One file for a writer, with its count of lines; a part of a long file has `part`, its first and last line, and `lines` counts the lines of the part. */
export interface NoteFile {
  path: string;
  lines: number;
  part?: [number, number];
}

export interface NoteGroup {
  name: string; // letters, digits and "-"; the same for the same files
  area?: string; // the id of the node of the top diagram that holds these files
  files: NoteFile[];
  lines: number;
}

export interface NoteGroups {
  groups: NoteGroup[];
  skipped: { count: number; why: string };
}

/** The fingerprint of a text: what the map keeps for a file with no code worth a note, so that a changed file is asked for again. */
export const fingerprint = (text: string): string => createHash('sha1').update(text).digest('hex');

/** The notes of files of a stored map as a source of notes, with no note of a diagram. */
export const fileNotesSource = (stored: StoredMap): NoteSource => mapSource({ ...stored, map: { ...stored.map, diagrams: [] } });

/** True when the text says in its first lines that a tool wrote it. */
const isGeneratedText = (text: string): boolean => GENERATED_MARK.test(text.split('\n', 6).join('\n'));

/** The area of a path: the id of the first node of the top diagram whose paths hold it. */
export function areaOf(map: RepoMap | undefined, path: string): string | undefined {
  const top = map?.diagrams.find((diagram) => !diagram.parent);
  return Object.entries(top?.nodePaths ?? {}).find(([, paths]) => paths.some((entry) => entry === path || (entry.endsWith('/') && path.startsWith(entry))))?.[0];
}

/** The areas of the top diagram in their order, then undefined for the files in no area. */
export const areaOrder = (map: RepoMap | undefined): (string | undefined)[] => [...Object.keys(map?.diagrams.find((diagram) => !diagram.parent)?.nodePaths ?? {}), undefined];

export const slug = (area = 'other'): string => area.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 24) || 'other';

/** The code files of a repo with their text, in the order of their paths, and how many it left out: generated files, files of more than 20,000 lines and files with no text. */
export function codeFiles(folder: string): { files: { path: string; text: string }[]; skipped: number } {
  const files: { path: string; text: string }[] = [];
  let skipped = 0;
  for (const path of (repoFiles(folder) ?? []).filter((one) => CODE_ENDINGS.test(one) && !GENERATED_NAME.test(one) && !DRAFT_NAME.test(one.split('/').pop()!)).sort()) {
    const text = fileText(folder, path);
    if (text === undefined || !text.trim() || text.includes('\0') || isGeneratedText(text) || lineCount(text) > MAX_FILE_LINES) skipped++;
    else files.push({ path, text });
  }
  return { files, skipped };
}

function groupOf(area: string | undefined, files: NoteFile[]): NoteGroup {
  const name = `${slug(area)}-${fingerprint(files.map((file) => `${file.path}:${file.part?.join('-') ?? '-'}`).join('\n')).slice(0, 6)}`;
  return { name, ...(area ? { area } : {}), files, lines: files.reduce((sum, file) => sum + file.lines, 0) };
}

// ----- the parts of a long file -----

/** A line that belongs to the definition under it: a comment, a doc comment, a decorator, an annotation, an attribute or a template header. */
const ABOVE = /^\s*(\/\/|\/\*|\*|#|@|\[|template\s*<)/;
const DECORATOR = /^\s*(@|#\[|\[)/; // the first line of a decorator, an annotation or an attribute
/** How many more brackets a line closes than it opens. */
const closes = (line: string): number => (line.match(/[)\]}]/g)?.length ?? 0) - (line.match(/[([{]/g)?.length ?? 0);

/**
 * The first line of the block right above a definition that starts at line `first` (from 1): its comments, doc comment, decorators or attributes, also a
 * decorator over several lines. A blank line ends the block. The block never reaches `floor`, the last line of the definition before.
 */
function blockStart(lines: string[], first: number, floor: number): number {
  let start = first;
  while (start - 1 > floor) {
    const line = lines[start - 2]; // the line above the block
    if (ABOVE.test(line)) {
      start--;
      continue;
    }
    // The last line of a decorator over several lines: go up to the line that opens its brackets, and take it all when that line is a decorator.
    let open = closes(line);
    if (open <= 0) break;
    let at = start - 1;
    while (open > 0 && at - 1 > floor) open += closes(lines[--at - 1]);
    if (open > 0 || !DECORATOR.test(lines[at - 1])) break;
    start = at;
  }
  return start;
}

/**
 * The lines where a long file may be cut, each the first line of a new part. A cut stands between two definitions of the finder (definitionsOf), on the
 * first line of the comments or decorators right above the next one. No function or method spans it; a class spans it only when it falls between two of
 * its methods. The next definition stands at the left edge, or as deep as the methods of the class: so no cut falls inside a function that the finder
 * does not see, such as a test inside a call of another test.
 */
function cutsOf(path: string, text: string): number[] {
  const lines = text.split('\n');
  const indent = (line: number): number => lines[line - 1].length - lines[line - 1].trimStart().length;
  const found = definitionsOf(path, text);
  const cuts = new Set<number>();
  for (const next of found) {
    const before = found.filter((one) => one.lines[1] < next.lines[0]);
    if (!before.length) continue; // the first definition: nothing to cut from
    const cut = blockStart(lines, next.lines[0], Math.max(...before.map((one) => one.lines[1])));
    const depth = indent(next.lines[0]);
    const across = found.filter((one) => one.lines[0] < cut && one.lines[1] >= cut);
    // A class that spans the cut holds the next definition as one of its methods (a definition inside it as deep as the least deep), and one before the cut.
    const betweenMethods = (type: (typeof found)[number]): boolean => {
      const methods = found.filter((one) => one.lines[0] > type.lines[0] && one.lines[1] <= type.lines[1]);
      return type.kind === 'class' && methods.includes(next) && depth === Math.min(...methods.map((one) => indent(one.lines[0])))
        && methods.some((one) => one.lines[1] < cut && indent(one.lines[0]) === depth);
    };
    if (across.length ? across.every(betweenMethods) : depth === 0) cuts.add(cut);
  }
  return [...cuts].sort((a, b) => a - b);
}

/**
 * The parts of a code file, each [first line, last line]. A file of more than 600 lines is cut at the safe cut nearest to 400 lines from the start of each
 * part, within 150 lines before or after; with no safe cut there, the part grows to the next one. A last part of fewer than 150 lines joins the part before.
 * A shorter file, or one with no safe cut (also a language that the finder does not know), is one part: the whole file.
 */
export function partsOf(path: string, text: string): [number, number][] {
  const total = lineCount(text);
  const cuts = total > LONG_FILE ? cutsOf(path, text) : [];
  const parts: [number, number][] = [];
  let from = 1;
  for (;;) {
    const aim = from + PART_LINES;
    const near = cuts.filter((one) => Math.abs(one - aim) <= PART_REACH).sort((a, b) => Math.abs(a - aim) - Math.abs(b - aim) || a - b)[0];
    const cut = near ?? cuts.find((one) => one > aim + PART_REACH);
    if (cut === undefined || total - cut + 1 < PART_REACH) break;
    parts.push([from, cut - 1]);
    from = cut;
  }
  return [...parts, [from, total]];
}

/**
 * The code files of the repo that need notes, in groups for the notes writers. A file needs notes when the map has none for it, or fewer than 8 of 10 of its notes still stand at the text of their lines;
 * a file that a writer called empty stays out while its text is the same. With `all`, every code file. A group holds whole files of one area of the top diagram, in the order of their paths,
 * about 400 lines in sum; a file of more than 400 lines is a group of its own. A file of more than 600 lines is cut into parts (partsOf), each a group of its own: a part needs notes while no
 * note and no skip starts in its lines, or while its file needs notes. The groups are listed largest first.
 */
export function noteGroups(folder: string, stored: StoredMap | undefined, all = false): NoteGroups {
  const map = stored?.map;
  const source = stored && fileNotesSource(stored);
  const noted = new Map<string, number>();
  for (const note of map?.fileNotes ?? []) noted.set(note.file, (noted.get(note.file) ?? 0) + 1);
  const { files, skipped } = codeFiles(folder);
  const wanted = new Map<string | undefined, NoteFile[]>(); // by area, in the order of the paths
  for (const { path, text } of files) {
    const count = noted.get(path) ?? 0;
    const standing = source && count ? notesOfFile([source], path, text, () => undefined).notes : [];
    const needs = count ? standing.length / count < ENOUGH : map?.noNotes?.[path] !== fingerprint(text);
    const parts = partsOf(path, text);
    // Every part of a file that needs notes. Of a file whose notes stand, each part where no note and no skip starts: its writer failed.
    const starts = [...standing.map((note) => note.lines[0]), ...(map?.skips ?? []).filter((skip) => skip.file === path).map((skip) => skip.lines[0])];
    const listed = all || needs ? parts : count && parts.length > 1 ? parts.filter(([from, to]) => !starts.some((line) => line >= from && line <= to)) : [];
    const area = areaOf(map, path);
    for (const part of listed) wanted.set(area, [...(wanted.get(area) ?? []), { path, lines: part[1] - part[0] + 1, ...(parts.length > 1 ? { part } : {}) }]);
  }

  const groups: NoteGroup[] = [];
  for (const area of areaOrder(map)) {
    let current: NoteFile[] = [];
    const close = (): void => {
      if (current.length) groups.push(groupOf(area, current));
      current = [];
    };
    for (const file of wanted.get(area) ?? []) {
      if (file.part || (current.length && current.reduce((sum, one) => sum + one.lines, 0) + file.lines > GROUP_LINES)) close();
      current.push(file);
      if (file.part) close(); // a part is a group of its own
    }
    close();
  }
  return { groups: largestFirst(groups, (group) => group.lines), skipped: { count: skipped, why: 'generated files, files of more than 20,000 lines, and files with no text' } };
}

// ----- the work for the process writers -----

const GROUP_NOTES = 150; // the size of a group of a split area, so that no process writer has a long tail
const SPLIT_NOTES = 200; // an area with more notes than this is split by folder

export interface ProcessGroup {
  name: string; // letters, digits and "-"; the same for the same files
  area?: string; // the id of the node of the top diagram that holds these files
  files: { path: string; notes: number }[];
  notes: number;
  why?: string; // why it is listed: no process yet, stale processes, notes in no process
}

/**
 * The work for the process writers: one group for each area of the top diagram, with its code files and their count of notes; an area with more than about 200 notes is
 * split by folder into groups of about 150 notes, and the files in no area form their own groups. The notes of test files need no process, so their files are in no group.
 * By default only a group with no process yet, a stale process, or notes in no process; with `all`, every group. The groups are listed largest first, by
 * their notes.
 */
export function processGroups(map: RepoMap, all = false): { groups: ProcessGroup[]; testNotes: number } {
  const count = new Map<string, number>();
  for (const note of notesNeedingProcess(map)) count.set(note.file, (count.get(note.file) ?? 0) + 1);
  const sum = (paths: string[]): number => paths.reduce((total, path) => total + count.get(path)!, 0);
  const byArea = new Map<string | undefined, string[]>();
  for (const path of [...count.keys()].sort()) byArea.set(areaOf(map, path), [...(byArea.get(areaOf(map, path)) ?? []), path]);
  const groups: ProcessGroup[] = [];
  for (const area of areaOrder(map)) {
    const paths = byArea.get(area) ?? [];
    let current: string[] = [];
    const close = (): void => {
      if (current.length) groups.push({ name: `${slug(area)}-${fingerprint(current.join('\n')).slice(0, 6)}`, ...(area ? { area } : {}), files: current.map((path) => ({ path, notes: count.get(path)! })), notes: sum(current) });
      current = [];
    };
    if (sum(paths) <= SPLIT_NOTES) current = paths;
    else {
      // Split by folder: the files of one folder stay together while the group has room, and a folder that is too large alone is cut in the order of its paths.
      const folders = new Map<string, string[]>();
      for (const path of paths) folders.set(path.slice(0, path.lastIndexOf('/') + 1), [...(folders.get(path.slice(0, path.lastIndexOf('/') + 1)) ?? []), path]);
      for (const inFolder of folders.values()) {
        if (sum(current) + sum(inFolder) > GROUP_NOTES) close();
        for (const path of inFolder) {
          if (current.length && sum(current) + count.get(path)! > GROUP_NOTES) close();
          current.push(path);
        }
      }
    }
    close();
  }
  const keys = noteKeys(map);
  const left = new Map<string, number>();
  for (const note of notesInNoProcess(map)) left.set(note.file, (left.get(note.file) ?? 0) + 1);
  const listed = largestFirst(groups, (group) => group.notes).map((group) => {
    const own = (map.processes ?? []).filter((process) => process.group === group.name);
    const stale = own.filter((process) => goneSteps(process, keys).length).length;
    const notes = group.files.reduce((total, file) => total + (left.get(file.path) ?? 0), 0);
    const none = !own.length && !(map.notInProcess ?? []).some((one) => one.group === group.name);
    const why = [none ? 'no process yet' : '', stale ? `${stale} stale ${stale === 1 ? 'process' : 'processes'}` : '', notes && !none ? `${notes} ${notes === 1 ? 'note' : 'notes'} in no process` : ''].filter(Boolean).join(', ');
    return why ? { ...group, why } : group;
  });
  const testNotes = (map.fileNotes ?? []).length - notesNeedingProcess(map).length;
  return { groups: all ? listed : listed.filter((group) => group.why), testNotes };
}

/**
 * The check of one group of the process writers: what `apostil processes --group <name>` prints. Its writer runs it before it reports,
 * and the lead starts the second round of that group from it at once: the notes of its files in no process yet, with up to five keys for each file, and
 * the processes of the group whose steps name notes that are gone. `again`: whether the group needs a second round. Undefined for an unknown group.
 */
export function groupProcessFacts(map: RepoMap, name: string) {
  const group = processGroups(map, true).groups.find((one) => one.name === name);
  if (!group) return undefined;
  const facts = processFacts(map);
  const files = new Set(group.files.map((file) => file.path));
  const left = facts.notInProcess.files.filter((file) => files.has(file.file));
  const keys = noteKeys(map);
  const stale = (map.processes ?? []).filter((process) => process.group === name).map((process) => ({ id: process.id, gone: goneSteps(process, keys).length })).filter((one) => one.gone);
  const processes = (map.processes ?? []).filter((process) => process.group === name).length;
  return { group: name, processes, notInProcess: { count: left.reduce((sum, file) => sum + file.count, 0), files: left }, stale, again: left.length > 0 || stale.length > 0 };
}

/** The areas of the top diagram whose code files still wait for notes (a file in no area counts as the area ''), from the groups of the notes writers. */
export const areasWaitingForNotes = (groups: NoteGroup[]): Set<string> => new Set(groups.map((group) => group.area ?? ''));

/**
 * What `apostil process-groups` prints: the groups of the process writers of the areas whose notes are all saved, so that the process writers of an
 * area start as soon as its notes are saved, and `waiting`: how many areas still wait for notes. The lead runs it after each notes writer ends.
 */
export function readyProcessGroups(folder: string, stored: StoredMap, all = false): ReturnType<typeof processGroups> & { waiting: number } {
  const waiting = areasWaitingForNotes(noteGroups(folder, stored).groups);
  const listed = processGroups(stored.map, all);
  return { ...listed, groups: listed.groups.filter((group) => !waiting.has(group.area ?? '')), waiting: waiting.size };
}

/** How many code files need notes: what `apostil map` says in its hint. */
export const filesNeedingNotes = (folder: string, stored: StoredMap | undefined): number =>
  new Set(noteGroups(folder, stored).groups.flatMap((group) => group.files.map((file) => file.path))).size;

/** The notes of a file that the map holds, in the order of their lines. */
export const notesOf = (map: RepoMap, path: string): Note[] => (map.fileNotes ?? []).filter((note) => note.file === path).sort((a, b) => a.lines[0] - b.lines[0]);
