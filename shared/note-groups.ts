// The work for the notes writers: the code files of a repo that need notes, in groups of about 400 lines of whole files (build 84). A file longer than that is a group
// of its own, whole: one writer has it alone and saves its notes in parts (`ranges` of add-notes), so that nothing is lost when it stops.

import { createHash } from 'node:crypto';
import { fileText, lineCount, repoFiles } from './git';
import { mapSource, notesOfFile, type NoteSource } from './notes-beside-code';
import type { Note } from './change-file';
import { goneSteps, noteKeys, notesInNoProcess, notesNeedingProcess } from './processes';
import type { RepoMap } from './repo-map';
import type { StoredMap } from './store';

/** The endings of the names of code files. Everything else (data, text, lock files, pictures) gets no notes. The one list for the rule. */
const CODE_ENDINGS = /\.(ts|tsx|js|jsx|mjs|cjs|vue|svelte|py|ipynb|rb|go|rs|java|kt|kts|scala|swift|c|h|cc|cpp|hpp|cs|php|sh|bash|zsh|sql|r|lua|pl|ex|exs|erl|hs|ml|dart|zig|jl|m|mm)$/i;
const GENERATED_NAME = /\.(min\.(js|css)|d\.ts)$|\.pb\.go$|_pb2(_grpc)?\.py$|\.generated\./i;
const GENERATED_MARK = /@generated|auto-?generated|automatically generated|generated by|do not edit/i; // in the first lines of a generated file
const DRAFT_NAME = /^apostil-[a-z]+-.*\.json$/; // the draft of a writer is no code

export const MAX_FILE_LINES = 20000; // a file with more lines is left out
const GROUP_LINES = 400; // the size that a group grows to; a longer file is a group of its own
const ENOUGH = 0.8; // a file keeps its notes while this share of them still stands at the text of their lines

/** One file for a writer, always whole, with its count of lines. */
export interface NoteFile {
  path: string;
  lines: number;
}

export interface NoteGroup {
  name: string; // letters, digits and "-"; the same for the same files
  area?: string; // the id of the node of the top diagram that holds these files
  files: NoteFile[];
  lines: number;
}

export interface NoteGroups {
  groups: NoteGroup[];
  skipped: { count: number; why: string };
}

/** The fingerprint of a text: what the map keeps for a file with no code worth a note, so that a changed file is asked for again. */
export const fingerprint = (text: string): string => createHash('sha1').update(text).digest('hex');

/** The notes of files of a stored map as a source of notes, with no note of a diagram. */
export const fileNotesSource = (stored: StoredMap): NoteSource => mapSource({ ...stored, map: { ...stored.map, diagrams: [] } });

/** True when the text says in its first lines that a tool wrote it. */
const isGeneratedText = (text: string): boolean => GENERATED_MARK.test(text.split('\n', 6).join('\n'));

/** The area of a path: the id of the first node of the top diagram whose paths hold it. */
export function areaOf(map: RepoMap | undefined, path: string): string | undefined {
  const top = map?.diagrams.find((diagram) => !diagram.parent);
  return Object.entries(top?.nodePaths ?? {}).find(([, paths]) => paths.some((entry) => entry === path || (entry.endsWith('/') && path.startsWith(entry))))?.[0];
}

/** The areas of the top diagram in their order, then undefined for the files in no area. */
export const areaOrder = (map: RepoMap | undefined): (string | undefined)[] => [...Object.keys(map?.diagrams.find((diagram) => !diagram.parent)?.nodePaths ?? {}), undefined];

export const slug = (area = 'other'): string => area.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 24) || 'other';

/** The code files of a repo with their text, in the order of their paths, and how many it left out: generated files, files of more than 20,000 lines and files with no text. */
export function codeFiles(folder: string): { files: { path: string; text: string }[]; skipped: number } {
  const files: { path: string; text: string }[] = [];
  let skipped = 0;
  for (const path of (repoFiles(folder) ?? []).filter((one) => CODE_ENDINGS.test(one) && !GENERATED_NAME.test(one) && !DRAFT_NAME.test(one.split('/').pop()!)).sort()) {
    const text = fileText(folder, path);
    if (text === undefined || !text.trim() || text.includes('\0') || isGeneratedText(text) || lineCount(text) > MAX_FILE_LINES) skipped++;
    else files.push({ path, text });
  }
  return { files, skipped };
}

function groupOf(area: string | undefined, files: NoteFile[]): NoteGroup {
  const name = `${slug(area)}-${fingerprint(files.map((file) => `${file.path}:-`).join('\n')).slice(0, 6)}`;
  return { name, ...(area ? { area } : {}), files, lines: files.reduce((sum, file) => sum + file.lines, 0) };
}

/**
 * The code files of the repo that need notes, in groups for the notes writers. A file needs notes when the map has none for it, or fewer than 8 of 10 of its notes still stand at the text of their lines;
 * a file that a writer called empty stays out while its text is the same. With `all`, every code file. A group holds whole files of one area of the top diagram, in the order of their paths,
 * about 400 lines in sum; a file is never split, and a file of more than 400 lines is a group of its own.
 */
export function noteGroups(folder: string, stored: StoredMap | undefined, all = false): NoteGroups {
  const map = stored?.map;
  const source = stored && fileNotesSource(stored);
  const noted = new Map<string, number>();
  for (const note of map?.fileNotes ?? []) noted.set(note.file, (noted.get(note.file) ?? 0) + 1);
  const { files, skipped } = codeFiles(folder);
  const wanted = new Map<string | undefined, { path: string; text: string }[]>(); // by area, in the order of the paths
  for (const { path, text } of files) {
    const count = noted.get(path) ?? 0;
    const standing = source && count ? notesOfFile([source], path, text, () => undefined).notes.length : 0;
    const needs = count ? standing / count < ENOUGH : map?.noNotes?.[path] !== fingerprint(text);
    if (!all && !needs) continue;
    const area = areaOf(map, path);
    wanted.set(area, [...(wanted.get(area) ?? []), { path, text }]);
  }

  const groups: NoteGroup[] = [];
  for (const area of areaOrder(map)) {
    let current: NoteFile[] = [];
    const close = (): void => {
      if (current.length) groups.push(groupOf(area, current));
      current = [];
    };
    for (const { path, text } of wanted.get(area) ?? []) {
      const total = lineCount(text);
      if (current.length && current.reduce((sum, file) => sum + file.lines, 0) + total > GROUP_LINES) close();
      current.push({ path, lines: total });
    }
    close();
  }
  return { groups, skipped: { count: skipped, why: 'generated files, files of more than 20,000 lines, and files with no text' } };
}

// ----- the work for the process writers -----

const GROUP_NOTES = 400; // the size of a group of a split area
const SPLIT_NOTES = 500; // an area with more notes than this (about 400) is split by folder

export interface ProcessGroup {
  name: string; // letters, digits and "-"; the same for the same files
  area?: string; // the id of the node of the top diagram that holds these files
  files: { path: string; notes: number }[];
  notes: number;
  why?: string; // why it is listed: no process yet, stale processes, notes in no process
}

/**
 * The work for the process writers: one group for each area of the top diagram, with its code files and their count of notes; an area with more than about 400 notes is
 * split by folder, and the files in no area form their own groups. The notes of test files need no process, so their files are in no group.
 * By default only a group with no process yet, a stale process, or notes in no process; with `all`, every group.
 */
export function processGroups(map: RepoMap, all = false): { groups: ProcessGroup[]; testNotes: number } {
  const count = new Map<string, number>();
  for (const note of notesNeedingProcess(map)) count.set(note.file, (count.get(note.file) ?? 0) + 1);
  const sum = (paths: string[]): number => paths.reduce((total, path) => total + count.get(path)!, 0);
  const byArea = new Map<string | undefined, string[]>();
  for (const path of [...count.keys()].sort()) byArea.set(areaOf(map, path), [...(byArea.get(areaOf(map, path)) ?? []), path]);
  const groups: ProcessGroup[] = [];
  for (const area of areaOrder(map)) {
    const paths = byArea.get(area) ?? [];
    let current: string[] = [];
    const close = (): void => {
      if (current.length) groups.push({ name: `${slug(area)}-${fingerprint(current.join('\n')).slice(0, 6)}`, ...(area ? { area } : {}), files: current.map((path) => ({ path, notes: count.get(path)! })), notes: sum(current) });
      current = [];
    };
    if (sum(paths) <= SPLIT_NOTES) current = paths;
    else {
      // Split by folder: the files of one folder stay together while the group has room, and a folder that is too large alone is cut in the order of its paths.
      const folders = new Map<string, string[]>();
      for (const path of paths) folders.set(path.slice(0, path.lastIndexOf('/') + 1), [...(folders.get(path.slice(0, path.lastIndexOf('/') + 1)) ?? []), path]);
      for (const inFolder of folders.values()) {
        if (sum(current) + sum(inFolder) > GROUP_NOTES) close();
        for (const path of inFolder) {
          if (current.length && sum(current) + count.get(path)! > GROUP_NOTES) close();
          current.push(path);
        }
      }
    }
    close();
  }
  const keys = noteKeys(map);
  const left = new Map<string, number>();
  for (const note of notesInNoProcess(map)) left.set(note.file, (left.get(note.file) ?? 0) + 1);
  const listed = groups.map((group) => {
    const own = (map.processes ?? []).filter((process) => process.group === group.name);
    const stale = own.filter((process) => goneSteps(process, keys).length).length;
    const notes = group.files.reduce((total, file) => total + (left.get(file.path) ?? 0), 0);
    const none = !own.length && !(map.notInProcess ?? []).some((one) => one.group === group.name);
    const why = [none ? 'no process yet' : '', stale ? `${stale} stale ${stale === 1 ? 'process' : 'processes'}` : '', notes && !none ? `${notes} ${notes === 1 ? 'note' : 'notes'} in no process` : ''].filter(Boolean).join(', ');
    return why ? { ...group, why } : group;
  });
  const testNotes = (map.fileNotes ?? []).length - notesNeedingProcess(map).length;
  return { groups: all ? listed : listed.filter((group) => group.why), testNotes };
}

/** The areas of the top diagram whose code files still wait for notes (a file in no area counts as the area ''), from the groups of the notes writers. */
export const areasWaitingForNotes = (groups: NoteGroup[]): Set<string> => new Set(groups.map((group) => group.area ?? ''));

/**
 * What `apostil process-groups` prints (build 84): the groups of the process writers of the areas whose notes are all saved, so that the process writers of an
 * area start as soon as its notes are saved, and `waiting`: how many areas still wait for notes. The lead runs it after each notes writer ends.
 */
export function readyProcessGroups(folder: string, stored: StoredMap, all = false): ReturnType<typeof processGroups> & { waiting: number } {
  const waiting = areasWaitingForNotes(noteGroups(folder, stored).groups);
  const listed = processGroups(stored.map, all);
  return { ...listed, groups: listed.groups.filter((group) => !waiting.has(group.area ?? '')), waiting: waiting.size };
}

/** How many code files need notes: what `apostil map` says in its hint. */
export const filesNeedingNotes = (folder: string, stored: StoredMap | undefined): number =>
  new Set(noteGroups(folder, stored).groups.flatMap((group) => group.files.map((file) => file.path))).size;

/** The notes of a file that the map holds, in the order of their lines. */
export const notesOf = (map: RepoMap, path: string): Note[] => (map.fileNotes ?? []).filter((note) => note.file === path).sort((a, b) => a.lines[0] - b.lines[0]);
